    top = sorted(sig.items(), key=lambda x: -len(x[1]))[:8]
    A["residual"][f"{split}/{k}"] = {s: {"n": len(v), "top1": float(np.mean(v))} for s, v in sig.items()}
    md += ["", f"**{k}, {'shifted' if split == 'test_shifted' else 'original'} test set** "
           f"({len(sig)} distinct signatures; most frequent shown)", ""]
    table(["Attributes readable by the attacker", "Tickets", "Linkage top-1"],
          [[s, len(v), f3(np.mean(v))] for s, v in top])

