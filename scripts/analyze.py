def masked_precision(split):
    """Share of characters inside S3-predicted spans that belong to a gold identity span."""
    inside = total = 0
    for t in DATA[split]:
        gold = np.zeros(len(t["text"]), bool)
        for s in t["spans"]:
            if s["level"] != "task":
                gold[s["start"]:s["end"]] = True
        for a, b in S3SPANS[(split, t["tid"])]:
            seg = gold[a:b]
            inside += int(seg.sum())
            total += len(seg) - t["text"][a:b].count(" ")
            inside -= int(sum(gold[a + i] for i, ch in enumerate(t["text"][a:b]) if ch == " "))
    return inside / total if total else float("nan")


