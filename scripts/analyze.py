def ci(v):
    v = np.asarray([x for x in v if x is not None and not (isinstance(x, float) and np.isnan(x))], dtype=float)
    b = np.random.default_rng(SEED).choice(v, (NB, len(v))).mean(1)
    return {"point": float(v.mean()), "lo": float(np.percentile(b, 2.5)), "hi": float(np.percentile(b, 97.5)),
            "n": int(len(v))}


def paired_ci(a, b):
    """Bootstrap interval of mean(a - b) over paired observations (same index = same author)."""
    return ci(np.asarray(a, float) - np.asarray(b, float))


